LAYER={"m":"mechanical","b":"browser","j":"judgment"}
SEV={"B":"blocker","W":"important","P":"polish"}
FIX={"a":"claude","c":"choice","u":"user"}

import json, csv, collections, os
here=os.path.dirname(os.path.abspath(__file__))
rows=[]; seen=set()
for ck,cn,items in CATS:
    for (i,t,l,s,f,v,c,h) in items:
        assert i not in seen, i; seen.add(i); assert i.startswith(ck+"."), i
        rows.append({"id":i,"category":ck,"categoryTitle":cn,"title":t,"layer":LAYER[l],"severity":SEV[s],"fixer":FIX[f],"v1":bool(v),"appliesWhen":c or "always","how":h})
out={"version":1,"count":len(rows),
     "facts":{"forms":"has forms","mail":"sends email","auth":"has login","db":"has a database","shop":"has payments","ai":"calls an AI model","he":"Hebrew site","i18n":"multiple languages","dark":"has dark mode","ads":"runs ad pixels"},
     "checks":rows}
json.dump(out,open(os.path.join(here,"checks.json"),"w"),indent=1)
with open(os.path.join(here,"checks.csv"),"w",newline="") as fh:
    w=csv.writer(fh); w.writerow(["id","category","title","layer","severity","fixer","v1","appliesWhen","how"])
    for r in rows: w.writerow([r["id"],r["categoryTitle"],r["title"],r["layer"],r["severity"],r["fixer"],"yes" if r["v1"] else "",r["appliesWhen"],r["how"]])
print(len(rows),"checks", sum(r["v1"] for r in rows),"v1", len(CATS),"categories")
for k in ("layer","severity","fixer"): print(k,dict(collections.Counter(r[k] for r in rows)))
